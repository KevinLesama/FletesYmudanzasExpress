-- ===========================================================================
-- Fletes Express - Esquema para PostgreSQL / Supabase
-- ---------------------------------------------------------------------------
-- COMO USARLO
--   1. Abrir Supabase > SQL Editor > New query.
--   2. Pegar TODO este archivo y ejecutarlo.
--   3. Después correr backend/sql/auth.sql (vincula las cuentas de Supabase
--      Auth con la tabla usuarios) y, si querés datos de ejemplo,
--      backend/sql/seed.sql.
--
-- ALCANCE
--   - Pensado para una base de datos VACIA (proyecto de Supabase nuevo).
--   - Es IDEMPOTENTE: usa CREATE TABLE IF NOT EXISTS e índices IF NOT EXISTS,
--     por lo que se puede ejecutar más de una vez sin romper nada.
--   - La base está en español: tablas, columnas, índices y restricciones.
--
-- ORDEN: respeta las dependencias (primero las tablas sin claves foráneas).
-- ===========================================================================

-- ---------------------------------------------------------------------------
-- USUARIOS
-- Administradores, choferes y clientes viven en la misma tabla, separados por
-- `rol`. Los clientes no acceden al sistema (son contactos de la empresa).
--
-- El login no vive acá: las cuentas se crean en Supabase Auth y se vinculan a
-- esta tabla por email (o por `auth_user_id`, que agrega backend/sql/auth.sql).
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS usuarios (
    id               text         PRIMARY KEY,   -- 'JA' (chofer), 'CLI-001' (cliente), 'ADM-01'
    rol              text         NOT NULL,      -- admin | chofer | cliente
    nombre           text         NOT NULL,
    telefono         text         NOT NULL,
    email            text,
    iniciales        text,                      -- avatar del chofer en la interfaz
    estado           text         NOT NULL DEFAULT 'Activo',
    tarifa_base      numeric(12,2) NOT NULL DEFAULT 0,
    tarifa_por_km    numeric(12,2) NOT NULL DEFAULT 0,
    tarifa_por_hora  numeric(12,2) NOT NULL DEFAULT 0,
    creado_en        timestamptz  NOT NULL DEFAULT now(),
    actualizado_en   timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_usuarios_rol   CHECK (rol IN ('admin', 'chofer', 'cliente')),
    CONSTRAINT ck_usuarios_estado CHECK (estado IN ('Activo', 'Inactivo')),
    CONSTRAINT uq_usuarios_rol_telefono UNIQUE (rol, telefono),
    CONSTRAINT uq_usuarios_email           UNIQUE (email)
);

-- Factores extras de la tarifa (los edita el chofer en "Mi configuración").
CREATE TABLE IF NOT EXISTS factores_tarifa (
    id          integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  text         NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    etiqueta    text         NOT NULL,
    monto       numeric(12,2) NOT NULL DEFAULT 0,
    posicion    integer      NOT NULL DEFAULT 0,
    creado_en   timestamptz  NOT NULL DEFAULT now(),
    actualizado_en timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_factores_tarifa_usuario_id ON factores_tarifa (usuario_id);

CREATE TABLE IF NOT EXISTS vehiculos (
    id               text         PRIMARY KEY,
    tipo             text         NOT NULL,
    capacidad_kg     integer      NOT NULL,
    estado           text         NOT NULL DEFAULT 'Disponible',
    nota_asignacion  text,
    creado_en        timestamptz  NOT NULL DEFAULT now(),
    actualizado_en   timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_vehiculos_estado CHECK (estado IN ('Disponible', 'Asignado', 'En taller')),
    CONSTRAINT ck_vehiculos_capacidad_positiva CHECK (capacidad_kg > 0)
);

-- ---------------------------------------------------------------------------
-- SOLICITUDES / VIAJES
-- Refleja lo que la interfaz muestra: cliente, estado, fecha y ventanas de
-- llegada y de servicio, recorrido, carga, asignación y dinero.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS solicitudes (
    id                    text         PRIMARY KEY,   -- FEX-1048
    cliente_id            text         NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    cliente_nombre        text         NOT NULL,
    telefono              text         NOT NULL,
    estado                text         NOT NULL DEFAULT 'Pendiente de revisión',
    fecha                 date         NOT NULL,

    llegada_desde         time         NOT NULL,
    llegada_hasta         time         NOT NULL,
    servicio_desde        time         NOT NULL,
    servicio_hasta        time         NOT NULL,

    origen_direccion      text         NOT NULL,
    origen_barrio         text         NOT NULL,
    origen_piso           text         NOT NULL,
    origen_ascensor       boolean      NOT NULL DEFAULT false,

    destino_direccion     text         NOT NULL,
    destino_barrio        text         NOT NULL,
    destino_piso          text         NOT NULL,
    destino_ascensor      boolean      NOT NULL DEFAULT false,

    carga_unidades        integer      NOT NULL DEFAULT 0,
    carga_fragil          boolean      NOT NULL DEFAULT false,
    carga_notas           text         NOT NULL DEFAULT '',

    chofer_id             text         REFERENCES usuarios(id) ON DELETE SET NULL,
    vehiculo_id           text         REFERENCES vehiculos(id) ON DELETE SET NULL,

    precio                numeric(12,2) NOT NULL DEFAULT 0,
    sena_requerida        numeric(12,2) NOT NULL DEFAULT 0,
    km_estimados          integer,
    horas_estimadas       integer,

    creado_en             timestamptz  NOT NULL DEFAULT now(),
    actualizado_en        timestamptz  NOT NULL DEFAULT now(),

    CONSTRAINT ck_solicitudes_estado CHECK (
        estado IN ('Pendiente de revisión', 'Pendiente de seña', 'Confirmada', 'Cancelada')
    ),
    CONSTRAINT ck_solicitudes_sena_no_negativa CHECK (sena_requerida >= 0),
    CONSTRAINT ck_solicitudes_precio_no_negativo CHECK (precio >= 0)
);
CREATE INDEX IF NOT EXISTS ix_solicitudes_fecha      ON solicitudes (fecha);
CREATE INDEX IF NOT EXISTS ix_solicitudes_estado     ON solicitudes (estado);
CREATE INDEX IF NOT EXISTS ix_solicitudes_cliente_id ON solicitudes (cliente_id);
CREATE INDEX IF NOT EXISTS ix_solicitudes_chofer_id  ON solicitudes (chofer_id);
CREATE INDEX IF NOT EXISTS ix_solicitudes_vehiculo_id ON solicitudes (vehiculo_id);

CREATE TABLE IF NOT EXISTS items_carga (
    id            integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitud_id  text         NOT NULL REFERENCES solicitudes(id) ON DELETE CASCADE,
    nombre        text         NOT NULL,
    unidades      integer      NOT NULL DEFAULT 1,
    nota          text,
    posicion      integer      NOT NULL DEFAULT 0,
    creado_en     timestamptz  NOT NULL DEFAULT now(),
    actualizado_en timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_items_carga_solicitud_id ON items_carga (solicitud_id);

-- ---------------------------------------------------------------------------
-- PAGOS
-- Un pago por cobro. En efectivo el chofer adjunta la foto del remito.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pagos (
    id               integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitud_id     text         NOT NULL REFERENCES solicitudes(id) ON DELETE CASCADE,
    concepto         text         NOT NULL,
    metodo           text         NOT NULL,
    recibido_por     text         NOT NULL,
    monto            numeric(12,2) NOT NULL,
    fecha            date         NOT NULL,
    notas            text,
    remito_nombre    text,
    remito_datos_url text,
    creado_en        timestamptz  NOT NULL DEFAULT now(),
    actualizado_en   timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_pagos_concepto      CHECK (concepto IN ('Seña', 'Saldo')),
    CONSTRAINT ck_pagos_metodo        CHECK (metodo IN ('Transferencia', 'Cuenta corriente', 'Efectivo')),
    CONSTRAINT ck_pagos_recibido_por  CHECK (recibido_por IN ('Administración', 'Chofer')),
    CONSTRAINT ck_pagos_monto_positivo CHECK (monto > 0)
);
CREATE INDEX IF NOT EXISTS ix_pagos_solicitud_id ON pagos (solicitud_id);
CREATE INDEX IF NOT EXISTS ix_pagos_fecha         ON pagos (fecha);

-- ===========================================================================
-- Notas
