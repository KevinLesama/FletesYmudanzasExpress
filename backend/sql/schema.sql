CREATE TABLE IF NOT EXISTS clients (
    id          integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text         NOT NULL,
    phone       text         NOT NULL,
    created_at  timestamptz  NOT NULL DEFAULT now(),
    updated_at  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uq_clients_name_phone UNIQUE (name, phone)
);

CREATE TABLE IF NOT EXISTS drivers (
    id             text         PRIMARY KEY,
    initials       text         NOT NULL,
    name           text         NOT NULL,
    phone          text         NOT NULL,
    status         text         NOT NULL DEFAULT 'Activo',
    base_rate      numeric(12,2) NOT NULL DEFAULT 0,
    rate_per_km    numeric(12,2) NOT NULL DEFAULT 0,
    rate_per_hour  numeric(12,2) NOT NULL DEFAULT 0,
    created_at     timestamptz  NOT NULL DEFAULT now(),
    updated_at     timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_drivers_status CHECK (status IN ('Activo', 'Inactivo'))
);

CREATE TABLE IF NOT EXISTS driver_factors (
    id          integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    driver_id   text         NOT NULL REFERENCES drivers(id) ON DELETE CASCADE,
    label       text         NOT NULL,
    amount      numeric(12,2) NOT NULL DEFAULT 0,
    position    integer      NOT NULL DEFAULT 0,
    created_at  timestamptz  NOT NULL DEFAULT now(),
    updated_at  timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_driver_factors_driver_id ON driver_factors (driver_id);

CREATE TABLE IF NOT EXISTS vehicles (
    id             text         PRIMARY KEY,
    type           text         NOT NULL,
    capacity_kg    integer      NOT NULL,
    status         text         NOT NULL DEFAULT 'Disponible',
    assigned_note  text,
    created_at     timestamptz  NOT NULL DEFAULT now(),
    updated_at     timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_vehicles_status CHECK (status IN ('Disponible', 'Asignado', 'En taller')),
    CONSTRAINT ck_vehicles_capacity_positive CHECK (capacity_kg > 0)
);

CREATE TABLE IF NOT EXISTS requests (
    id                    text         PRIMARY KEY,   -- FEX-1048
    client_id             integer      NOT NULL REFERENCES clients(id) ON DELETE RESTRICT,
    client_name           text         NOT NULL,
    phone                 text         NOT NULL,
    status                text         NOT NULL DEFAULT 'Pendiente de revisión',
    date                  date         NOT NULL,

    arrival_from          time         NOT NULL,
    arrival_to            time         NOT NULL,
    service_from          time         NOT NULL,
    service_to            time         NOT NULL,

    origin_address        text         NOT NULL,
    origin_barrio         text         NOT NULL,
    origin_floor          text         NOT NULL,
    origin_elevator       boolean      NOT NULL DEFAULT false,

    destination_address   text         NOT NULL,
    destination_barrio    text         NOT NULL,
    destination_floor     text         NOT NULL,
    destination_elevator  boolean      NOT NULL DEFAULT false,

    cargo_approx_units    integer      NOT NULL DEFAULT 0,
    cargo_fragile         boolean      NOT NULL DEFAULT false,
    cargo_notes           text         NOT NULL DEFAULT '',

    driver_id             text         REFERENCES drivers(id) ON DELETE SET NULL,
    vehicle_id            text         REFERENCES vehicles(id) ON DELETE SET NULL,

    price                 numeric(12,2) NOT NULL DEFAULT 0,
    deposit_required      numeric(12,2) NOT NULL DEFAULT 0,
    confirmed             boolean      NOT NULL DEFAULT false,
    estimated_km          integer,
    estimated_hours       integer,

    arrived_at            text,
    finished_at           text,
    remito_name           text,
    remito_data_url       text,

    created_at            timestamptz  NOT NULL DEFAULT now(),
    updated_at            timestamptz  NOT NULL DEFAULT now(),

    CONSTRAINT ck_requests_status CHECK (
        status IN ('Pendiente de revisión', 'Pendiente de seña', 'Confirmada', 'Cancelada')
    ),
    CONSTRAINT ck_requests_deposit_non_negative CHECK (deposit_required >= 0),
    CONSTRAINT ck_requests_price_non_negative CHECK (price >= 0)
);
CREATE INDEX IF NOT EXISTS ix_requests_date       ON requests (date);
CREATE INDEX IF NOT EXISTS ix_requests_status     ON requests (status);
CREATE INDEX IF NOT EXISTS ix_requests_client_id  ON requests (client_id);
CREATE INDEX IF NOT EXISTS ix_requests_driver_id  ON requests (driver_id);
CREATE INDEX IF NOT EXISTS ix_requests_vehicle_id ON requests (vehicle_id);

CREATE TABLE IF NOT EXISTS request_cargo_items (
    id          integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id  text         NOT NULL REFERENCES requests(id) ON DELETE CASCADE,
    name        text         NOT NULL,
    units       integer      NOT NULL DEFAULT 1,
    note        text,
    position    integer      NOT NULL DEFAULT 0,
    created_at  timestamptz  NOT NULL DEFAULT now(),
    updated_at  timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_request_cargo_items_request_id ON request_cargo_items (request_id);

CREATE TABLE IF NOT EXISTS incidents (
    id          text         PRIMARY KEY,   -- INC-1001
    request_id  text         NOT NULL REFERENCES requests(id) ON DELETE CASCADE,
    type        text         NOT NULL,
    description text         NOT NULL,
    time        text         NOT NULL,
    created_at  timestamptz  NOT NULL DEFAULT now(),
    updated_at  timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_incidents_request_id ON incidents (request_id);

CREATE TABLE IF NOT EXISTS payments (
    id           integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id   text         NOT NULL REFERENCES requests(id) ON DELETE CASCADE,
    concept      text         NOT NULL,
    method       text         NOT NULL,
    received_by  text         NOT NULL,
    amount       numeric(12,2) NOT NULL,
    date         date         NOT NULL,
    notes        text,
    created_at   timestamptz  NOT NULL DEFAULT now(),
    updated_at   timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_payments_concept     CHECK (concept IN ('Seña', 'Saldo')),
    CONSTRAINT ck_payments_method      CHECK (method IN ('Transferencia', 'Efectivo')),
    CONSTRAINT ck_payments_received_by CHECK (received_by IN ('Administración', 'Chofer')),
    CONSTRAINT ck_payments_amount_positive CHECK (amount > 0)
);
CREATE INDEX IF NOT EXISTS ix_payments_request_id ON payments (request_id);
CREATE INDEX IF NOT EXISTS ix_payments_date       ON payments (date);

