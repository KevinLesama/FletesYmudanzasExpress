-- CÓMO FUNCIONA HOY (ya implementado)
--   1. El navegador inicia sesión con Supabase (email + contraseña).
--   2. Supabase devuelve un JWT; el frontend lo manda en cada request como
--      `Authorization: Bearer <token>`.
