--     9. No intentar reabrir un viaje 'finalizada' ni 'cancelada': la base lo
--        rechaza y es a propósito (A.6).
--    10. Repetir las pruebas de este esquema contra la base real después de
--        migrar, incluidas las dos EXCLUDE (requieren btree_gist).
--
--   Fuera de alcance, decidido: no hay tabla de reclamos, no hay bitácora, no
--   hay login de clientes, no hay cuenta corriente. Si algo de eso aparece
--   como pedido, primero hay que cambiar una decisión de la sección A o C, no
--   agregar una tabla suelta.


