--   --     ON solicitudes (token_seguimiento)
--   --     WHERE token_seguimiento IS NOT NULL;
--   --
--   -- -- Un intento por teléfono y día, para frenar el spam más obvio.
--   -- CREATE TABLE IF NOT EXISTS intentos_landing (
--   --     id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
--   --     telefono    text        NOT NULL,
--   --     ip          inet,
