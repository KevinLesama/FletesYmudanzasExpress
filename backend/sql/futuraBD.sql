-- ===========================================================================
-- Fletes Express - Decisiones de diseño y trabajo pendiente
-- ---------------------------------------------------------------------------
-- QUÉ ES ESTE ARCHIVO
--   El registro de por qué la base quedó como quedó. NO se ejecuta: todo el
--   DDL de las secciones B y C está comentado a propósito.
--
--   Sirve para tres cosas:
--     1. Que la próxima persona entienda las decisiones sin preguntar.
--     2. Que no se "redescubran" opciones ya descartadas.
--     3. Que la deuda de la API quede escrita en algún lado visible.
--
-- CÓMO LEERLO
--   A) Decisiones tomadas      -> lo que está en schema.sql hoy
--   B) Landing pública         -> propuesta pendiente de aprobación
--   C) Lo que se descartó      -> y por qué (no reabrir sin motivo nuevo)
--   D) Trazabilidad            -> tabla vieja/columna vieja -> dónde vive ahora
--   E) Deuda de la API         -> lo que falta del lado del código
-- ===========================================================================


-- ===========================================================================
-- A) DECISIONES TOMADAS
-- ===========================================================================

-- A.1 Cinco tablas, sin incidentes ni bitácora
--   El esquema anterior tenía ocho: requests, clients, drivers, driver_factors,
--   vehicles, request_cargo_items, payments e incidents. Para una PYME de
--   ocho personas, tres de esas tablas no compraban nada:
--     * driver_factors  -> recargos por chofer que el negocio no usa (ver C.1)
--     * incidents       -> los problemas se resuelven por WhatsApp (ver C.2)
--     * (no había) bitácora -> auditar cada cambio es caro y nadie la lee (C.3)
--
--   Quedaron cinco:
--     usuarios     administradores, choferes y clientes
--     vehiculos    la flota
--     solicitudes  los viajes (incluye el remito)
--     items_carga  el detalle de la carga
--     pagos        los cobros
--
--   Regla que se sigue de acá: si una tabla nueva no reemplaza a una de estas
--   cinco, hay que justificarla muy bien. El costo de una tabla no es crearla:
--   es mantenerla coherente para siempre.

-- A.2 Los tres roles siguen en una sola tabla (decisión del equipo)
--   administrador, chofer y cliente comparten `usuarios` y se discriminan por
--   `rol`. Se evaluó separar en tres tablas y se descartó: el 90 % de los
--   datos es el mismo (nombre, teléfono, email, activo) y el panel ya trata a
--   las tres figuras de forma parecida.
--
--   El precio de esa decisión es que hay que impedir los cruces a mano:
--     * ck_usuarios_rol                  -> solo los tres valores
--     * ck_usuarios_tarifas / _licencia  -> tarifas y licencia solo en choferes
--     * ck_usuarios_email_personal       -> admin y chofer necesitan email
--   Y del lado del login: TODA búsqueda por email debe filtrar por rol (A.12).

-- A.3 El cliente NO es una cuenta (aunque comparta tabla)
--   Un cliente es un contacto de la empresa: tiene nombre, teléfono y a veces
--   email, pero no contraseña ni acceso. Por eso:
--     * `email` es opcional para clientes;
--     * `v_personal` (auth.sql) excluye a los clientes por definición;
--     * el login resuelve siempre contra v_personal o filtra por rol.
--   Si algún día el cliente tiene portal propio (sección B), eso NO cambia
--   esta decisión: el token de la landing es otra cosa, no un usuario.

-- A.4 Los roles de un viaje están atados con claves foráneas compuestas
--   El problema: impedir que un cliente figure como chofer de un viaje. No se
--   puede con un CHECK (PostgreSQL no admite subconsultas ahí). La solución:
--     solicitudes (cliente_id, cliente_rol) -> usuarios (id, rol)
--     solicitudes (chofer_id,  chofer_rol)  -> usuarios (id, rol)
--   con `cliente_rol` y `chofer_rol` constantes ('cliente' y 'chofer') y
--   uq_usuarios_id_rol UNIQUE (id, rol) como destino.
--
--   Efecto buscado: tampoco se puede cambiar el rol de una persona que ya
--   tiene viajes, porque la FK es ON UPDATE RESTRICT. Si un chofer se convierte
--   en administrador, hay que crear otra fila; el historial queda intacto.
--
--   MATCH SIMPLE (el default) hace que con chofer_id NULL la FK no se controle:
--   un viaje pendiente puede no tener chofer.

-- A.5 Identificadores
--   PKs: bigint GENERATED BY DEFAULT AS IDENTITY. BIGINT porque una PYME no
--   llega a 2.000 millones de viajes, pero migrar después es doloroso.
--   BY DEFAULT (no ALWAYS) para permitir cargar historial con IDs explícitos
--   si algún día hay que importar.
--
--   Código visible: solicitudes.codigo = 'FEX-' || lpad(nextval(...), 4, '0'),
--   con `solicitudes_codigo_seq` empezando en 1001. Es lo que ve el cliente y
--   el admin; el id no se muestra.
--
--   Los códigos PUEDEN tener huecos. El DEFAULT consume nextval() al construir
--   la fila y PostgreSQL no devuelve el número si el INSERT falla después
--   (choque de agenda, violación de CHECK, error de red). Es esperable y no se
--   corrige: el código identifica, no cuenta. No reutilizar números ni
--   "rellenar" huecos.
--
--   seed.sql inserta con código explícito, así que al final ajusta la
--   secuencia con setval(GREATEST(last_value, 1006)).

-- A.6 Estados del viaje: pendiente | confirmada | finalizada | cancelada
--   Se eliminaron 'Pendiente de revisión' y 'Pendiente de seña'. El primero
--   era una etapa de la landing (no un estado del viaje); el segundo mezclaba
--   agenda con cobranza. Cobranza se deriva en v_solicitudes.estado_cobro:
--   sin_pagos | parcial | cobrado | sobrepago.
--
--   'finalizada' se agregó después, a pedido del negocio: el admin necesita
--   leer "Finalizado" en el historial del panel, y el chofer necesita un
--   momento concreto de cierre para subir el remito.
--
--   Solo avanzan; el control vive en fn_validar_transicion_estado:
--       pendiente  -> confirmada | cancelada
--       confirmada -> finalizada | cancelada
--       finalizada -> (terminal)
--       cancelada  -> (terminal)
--   El INSERT no se valida: permite cargar historial y el seed.
--
--   Efecto colateral buscado: al pasar a 'finalizada' el viaje deja de estar
--   'confirmada', así que SALE de la agenda y libera chofer y vehículo sin
--   tocar las restricciones EXCLUDE.
--
--   'finalizada' es terminal a propósito. Si el cliente reclama algo después
--   de la entrega, eso NO es un cambio de estado: se gestiona por WhatsApp.
--   No hay tabla de reclamos ni se va a agregar.

-- A.7 El conflicto de agenda SOLO aplica a 'confirmada'
--   Se expresa con dos restricciones EXCLUDE USING gist sobre
--   tsrange(fecha + hora_desde, fecha + hora_hasta, '[)') con WHERE (estado =
--   'confirmada'):
--       ex_solicitudes_chofer_sin_solape
--       ex_solicitudes_vehiculo_sin_solape
--   Dos viajes pendientes pueden solaparse; confirmar uno que choque devuelve
--   el error 23P01 (exclusion_violation), que la API debe traducir a 409
--   Conflict. Cancelar o finalizar un viaje libera chofer y vehículo sin tocar
--   ninguna otra fila.
--
--   El rango es semiabierto '[)' para que un viaje que termina 10:00 y otro
--   que empieza 10:00 NO choquen.
--
--   Requiere la extensión btree_gist (GiST le da los operadores de igualdad
--   para chofer_id y vehiculo_id). Viene con postgresql-contrib y Supabase ya
--   la tiene disponible.

-- A.8 Un solo rango horario por viaje
--   Las cuatro columnas anteriores (llegada_desde/hasta + servicio_desde/
--   hasta) se redujeron a hora_desde / hora_hasta. El negocio no distingue
--   "llegada" de "servicio": el viaje ocupa una ventana y punto. Con cuatro
--   columnas, la agenda tenía dos fuentes de verdad y el solape se calculaba
--   distinto en cada pantalla.

-- A.9 Nada derivado se guarda
--   Saldo, total cobrado, cantidad de bultos, fragilidad, disponibilidad del
--   vehículo y del chofer NO son columnas: son vistas.
--     v_solicitudes          -> total_pagado, saldo, estado_cobro, bultos,
--                               tiene_fragil, precio_editado, remito_cargado
--     v_remitos_pendientes   -> viajes con efectivo y sin foto de remito
--     v_agenda_confirmada    -> qué está ocupado y con quién
--     v_recaudacion_usuario  -> cobros por persona y mes
--     v_personal             -> admin y choferes habilitados para el login
--
--   Fue la causa principal de inconsistencias del esquema anterior: se
--   guardaba `assigned_note` en el vehículo y `confirmed` en el viaje, y
--   quedaban desactualizados apenas algo cambiaba.

-- A.10 Dinero
--   Tres precios, con roles distintos:
--     precio_calculado -> lo que dio la fórmula (tarifa base + km + hora)
--     precio_final     -> lo que se cobra
--     precio_editado   -> NO se guarda: es precio_final <> precio_calculado,
--                         y se expone en v_solicitudes. Si el admin lo edita,
--                         queda auditoría en precio_modificado_por/_en.
--
--   La seña requerida es el 50 % de precio_final (regla de presentación). No
--   se guarda: se calcula. Lo efectivamente cobrado sale de pagos.
--
--   `pagos.monto` es numeric(12,2) y > 0. `fn_validar_pago` impide superar el
--   precio final y bloquea la fila del viaje con FOR UPDATE para que dos
--   cobros simultáneos no puedan pasar los dos.
--
--   No existe "cuenta corriente" (ver C.5): un viaje se cobra o queda con
--   saldo visible; no hay crédito a favor del cliente.

-- A.11 Sin DELETE de entidades
--   `fn_prohibir_borrado` devuelve 23001 (restrict_violation) en usuarios,
--   vehiculos, solicitudes y pagos. La baja es lógica:
--     usuarios     -> activo = false
--     vehiculos    -> activo = false (o estado = 'fuera_de_servicio')
--     solicitudes  -> estado = 'cancelada' + motivo_cancelacion
--     pagos        -> se corrigen con UPDATE, no se borran
--
--   Excepción: items_carga SÍ admite DELETE. Es una línea editable del viaje,
--   no una entidad con historial propio. Si el cliente saca un sillón de la
--   mudanza, esa línea se borra y listo.

-- A.12 Seguridad
--   RLS activo SIN políticas en las cinco tablas, y permisos revocados a
--   anon/authenticated (también en las vistas: se ejecutan con los permisos
--   del dueño, así que revocar en las tablas no alcanza).
--
--   La API entra por DATABASE_URL con un rol que saltea RLS, así que el acceso
--   real lo decide la API. Esto es a propósito: hay una sola puerta y está en
--   el backend. Si algún día el frontend usa supabase-js directo, hay que
--   escribir políticas ANTES de habilitar el acceso REST.
--
--   Consecuencia importante: la base NO sabe quién es el usuario. No puede
--   validar "solo el chofer asignado puede finalizar este viaje". Eso es
--   autorización de la API (sección E).

-- A.13 Sin datos duplicados del cliente en el viaje
--   Se eliminaron solicitudes.cliente_nombre y solicitudes.telefono: son
--   atributos de usuarios.cliente_id. Una sola fuente de verdad. Si el cliente
--   cambia de teléfono, se actualiza una fila y todos los viajes lo ven.

-- A.14 El remito es un papel físico, uno por viaje
--   El chofer completa el remito al terminar la entrega, le saca una foto y
--   la sube desde su vista. Ese momento es el cierre del viaje.
--
--   Se modeló como atributos del viaje (no del pago) porque es UNO por viaje:
--   un viaje puede tener seña y saldo cobrados por separado y una sola
--   entrega. Ponerlo en pagos obligaba a repetir la foto o a elegir cuál de
--   los dos pagos es "el bueno".
--
--   Columnas: remito_numero (talonario, único), remito_ruta y remito_nombre
--   (archivo en Storage), remito_subido_por_id, receptor_nombre y
--   receptor_documento (quien firmó la conformidad; no es usuario).
--
--   Cuándo es obligatorio: solo si hubo cobros en efectivo. Con transferencia
--   el movimiento bancario es la prueba y el sistema no pide nada.
--   Dos disparadores cierran el circuito:
--     * fn_validar_cierre_viaje -> no se finaliza con efectivo y sin remito.
--     * fn_validar_pago         -> no se registra efectivo en un viaje ya
--                                  finalizado sin remito (el saldo suele
--                                  cargarse después del cierre).
--   v_remitos_pendientes es la cola que ve el chofer.
--
--   Lo que NO se guarda: el archivo. Ni binario ni data URL. La foto vive en
--   Supabase Storage y la base solo apunta a la ruta. Las políticas del bucket
--   (quién sube, quién lee) son configuración de Supabase, no de este esquema:
--   las define la API.


-- ===========================================================================
-- B) LANDING PÚBLICA DE CLIENTES (pendiente de aprobación)
-- ===========================================================================
--
-- OBJETIVO
--   Que un cliente cargue su solicitud desde la web sin usuario ni contraseña
--   y que aparezca en el panel como 'pendiente'.
--
-- QUÉ YA SIRVE
--   * solicitudes.estado = 'pendiente' es exactamente "falta revisar".
--   * El cliente se crea o reutiliza en usuarios con rol 'cliente'.
--   * El viaje entra sin chofer, sin vehículo y sin cotizar: los CHECK lo
--     permiten.
--   * La API puede exponer un endpoint público que solo haga INSERT de
--     solicitudes pendientes, sin tocar el resto del esquema.
--
-- QUÉ FALTA DECIDIR
--   * ¿Cómo se evita el spam? (captcha, rate limit por IP, teléfono repetido)
--   * ¿El cliente puede ver el estado de su solicitud? Si sí, hace falta un
--     token opaco por solicitud; nunca el código FEX solo, porque es adivinable.
--   * ¿Qué datos son obligatorios en la landing? Hoy la base exige fecha,
--     ventana horaria, origen y destino; el resto es opcional.
--
-- DDL PROPUESTO (NO EJECUTAR: comentado a propósito)
--
--   -- Token de seguimiento para la landing. Opaco y aleatorio; no es login.
--   -- ALTER TABLE solicitudes
