-- ===========================================================================
-- C) LO QUE SE DESCARTÓ (y por qué no se reabre sin motivo nuevo)
-- ===========================================================================

-- C.1 Factores de tarifa por chofer (driver_factors)
--   La tabla existía con recargos fijos por chofer ("espera por ascensor",
--   "carga frágil"). El negocio cobra un precio por viaje, no una suma de
--   conceptos, y nadie usaba esos factores. Se eliminó.
--   Si algún día se necesita detallar el precio, el lugar es una columna de
--   texto en solicitudes o una tabla de conceptos, no una por chofer.

-- C.2 Incidentes (incidents)
--   Se cargaban demoras y problemas por viaje. En la práctica se resuelven por
--   WhatsApp y nadie los carga en el panel. Se eliminó. Tampoco hay tabla de
--   reclamos post-entrega: 'finalizada' es terminal y el reclamo es
--   conversación, no estado.

-- C.3 Bitácora de operaciones (auditoría)
--   Se evaluó una tabla `operaciones` que registrara cada cambio. Para ocho
--   personas y un panel chico, el costo de mantenerla y leerla supera el
--   beneficio. Lo que sí se audita es lo que tiene impacto económico:
--   precio_modificado_por/_en y remito_subido_por_id.
--   Si en el futuro hay que auditar de verdad, la vía es un trigger genérico
--   con jsonb, no una tabla por entidad.

-- C.4 Clientes con login
--   Se evaluó que el cliente entre a ver sus viajes. Se descartó: agrega
--   gestión de cuentas, recuperación de contraseña y soporte, para un volumen
--   que se maneja por teléfono. La landing (sección B) cubre la necesidad real
--   (cargar la solicitud) sin crear cuentas.

-- C.5 Método de pago "cuenta corriente"
--   Se evaluó cobrar a fin de mes a clientes recurrentes. Se descartó: la
--   empresa cobra seña y saldo, y el saldo visible en v_solicitudes ya dice
--   quién debe. Una cuenta corriente de verdad requiere límites, vencimientos
--   y conciliación; no es una columna más.

-- C.6 Guardar el remito como data URL o binario
--   Se descartó explícitamente. Un data URL en una columna text infla la base,
--   rompe los backups y no se puede servir con cache. La base guarda la RUTA
--   en Storage; el archivo vive en el bucket.

-- C.7 Estado "pendiente de revisión" / "pendiente de seña"
--   Ver A.6. Eran estados de la landing y de la cobranza disfrazados de estado
--   del viaje. Hoy: 'pendiente' es "falta revisar" y la cobranza se deriva.

-- C.8 Columna booleana `confirmed`
--   El esquema anterior tenía `confirmed` además de `status`. Dos fuentes de
--   verdad para lo mismo. Hoy el estado es una sola columna con CHECK.

-- C.9 `assigned_note` en el vehículo
--   Guardaba "asignado a FEX-1047 hasta 14:00" como texto. Se desactualizaba
--   solo. Hoy la asignación se deriva de v_agenda_confirmada.

-- C.10 Cuatro ventanas horarias (llegada + servicio)
--   Ver A.8.

-- C.11 `received_by` como texto en pagos
--   "Administración" o "Chofer" no identifican a nadie. Hoy es
--   recibido_por_id -> usuarios(id), y v_recaudacion_usuario puede agrupar por
--   persona.


